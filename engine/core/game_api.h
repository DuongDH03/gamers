#pragma once

// A game's description: everything an app needs from a game, as plain data
// and plain function pointers. The apps ask "which game?" through this, and
// never name a game's namespace.
//
// A game can be linked two ways from the same sources (spec
// docs/specs/2026-11-12-mouse-and-hot-reload.md, part B):
//   - statically into the exe (release builds, bench, tests): the game hands
//     its GameApi over through an ordinary function (sandbox::game_api());
//   - as a module (a DLL / shared library) that a running app can swap
//     between frames: the module exports one C function,
//
//       extern "C" const scraps::GameApi* scraps_game_api();
//
//     defined with SCRAPS_GAME_EXPORT (below), and only in the module build,
//     so the static and module builds never clash on that symbol.
//
// The module holds code only. The exe owns every piece of state (the World
// above all, which is plain data with no pointers, Rule 5) and lends it to
// the module's functions; nothing the exe keeps may point into the module
// across a swap. That is why SoundEvents carries copies of names, not
// pointers, and why apps copy `name` and `bindings` when they load a module.

#include <array>
#include <cstddef>
#include <cstdint>
#include <vector>

#include "core/boundary_hash.h"  // generated by CMake (cmake/ScrapsBoundaryHash.cmake)
#include "core/command.h"
#include "core/entity.h"
#include "core/jobs.h"
#include "core/level.h"
#include "core/simulate.h"
#include "core/world.h"
#include "platform/input.h"

// The exe and a game module pass std::vector storage back and forth (a
// module's simulate may grow World::entities, the exe frees it later), so
// both must use one heap: the shared C runtime. With MSVC that is /MD (or
// /MDd), CMake's default; the static runtime (/MT) gives every DLL a heap of
// its own, and freeing a block from another heap corrupts memory.
#if defined(_MSC_VER) && !defined(_DLL)
#error "Scraps game modules need the shared C runtime (/MD or /MDd): the exe and the module must share one heap. Do not build with /MT (CMAKE_MSVC_RUNTIME_LIBRARY MultiThreaded)."
#endif

namespace scraps {

// Bump when GameApi, GameBinding, GameUiCommand or SoundEvents change shape
// or meaning. History: 1 = first version; 2 = GameBinding can name a gamepad
// button; 3 = GameApi lists the game's UI commands (ui_commands).
constexpr std::uint32_t kGameApiVersion = 3;

// One input binding of a game: a key, a mouse button or a gamepad button
// sends `command`. Exactly one of the three is set; the others keep their
// "none" value (Key::kUnknown, MouseButton::kCount, GamepadButton::kCount).
// Use key_binding() / button_binding() / pad_binding().
struct GameBinding {
  Key key = Key::kUnknown;
  MouseButton button = MouseButton::kCount;
  CommandType command = CommandType::kNone;
  GamepadButton pad = GamepadButton::kCount;
};

constexpr GameBinding key_binding(Key key, CommandType command) {
  GameBinding binding;
  binding.key = key;
  binding.command = command;
  return binding;
}

constexpr GameBinding button_binding(MouseButton button, CommandType command) {
  GameBinding binding;
  binding.button = button;
  binding.command = command;
  return binding;
}

constexpr GameBinding pad_binding(GamepadButton pad, CommandType command) {
  GameBinding binding;
  binding.pad = pad;
  binding.command = command;
  return binding;
}

// The most bindings an app takes from a game (Controls has 12 slots in all).
constexpr std::size_t kMaxGameBindings = 12;

// A game command a UI may send by name (spec 2026-11-14, part 6a): a UI
// button "drop coin" sends {"type":"action","name":"command","command":
// "drop_coin"}, and the app queues `command` for the local player at the
// next tick (Rule 1: the UI never touches the World). `name` is 1 to 31
// ASCII letters, digits, '_' or '-', unique within the game; it lives in the
// game's code, so apps copy it. `command` is a game or engine command that a
// client may send (not kNone, not server-only).
struct GameUiCommand {
  const char* name;
  CommandType command;
};

constexpr std::size_t kMaxGameUiCommands = 8;
constexpr std::size_t kGameUiCommandNameCapacity = 32;  // 31 characters and the '\0'

// What the local player should hear for one tick, as sound names from the
// scene ("jump", "coin"). The names are copied in, so nothing here points
// into game code that may be unloaded before the sounds are played.
struct SoundEvents {
  static constexpr std::size_t kMaxEvents = 4;
  static constexpr std::size_t kNameCapacity = 16;  // 15 characters and the '\0'

  std::array<std::array<char, kNameCapacity>, kMaxEvents> names{};
  std::size_t count = 0;

  // Ignored when full; a longer name is truncated.
  void add(const char* name) {
    if (count >= kMaxEvents || name == nullptr) return;
    std::array<char, kNameCapacity>& out = names[count++];
    std::size_t i = 0;
    for (; i + 1 < kNameCapacity && name[i] != '\0'; ++i) out[i] = name[i];
    out[i] = '\0';
  }
  const char* name(std::size_t i) const { return names[i].data(); }
};

struct GameApi {
  std::uint32_t api_version;  // kGameApiVersion as the game was built; first, so it can always be read
  std::uint64_t layout_hash;  // kGameLayoutHash as the game was built
  const char* name;           // "sandbox"; copy it, it lives in the game's code
  // The game's rules (Rule 1). The Server and the Client call it every tick.
  SimulateFn simulate;
  // Input bindings the game wants on top of the engine's movement keys.
  const GameBinding* bindings;
  std::size_t binding_count;
  // Presentation only: what the local player hears for one tick, comparing
  // two worlds a tick apart. `out` arrives empty. May be nullptr.
  void (*sound_events)(const World& before, const World& after, PlayerId player, SoundEvents& out);
  // Presentation only: a short status for the HUD ("coins 3"), written into
  // `out` (`size` bytes, always terminated). May be nullptr.
  void (*hud)(const World& world, PlayerId player, char* out, std::size_t size);
  // Version 3: the game commands a UI may send by name (GameUiCommand), at
  // most kMaxGameUiCommands. May be nullptr with a count of 0.
  const GameUiCommand* ui_commands;
  std::size_t ui_command_count;
};

// The C entry point every game module exports, and its type.
constexpr const char* kGameApiSymbol = "scraps_game_api";
using GameApiEntry = const GameApi* (*)();

// Bump by hand when something crosses the boundary that kGameLayoutHash
// cannot see: a compiler flag that changes layouts, or an engine .cpp other
// than core/jobs.cpp and core/world.cpp that starts to share state or rules
// with the exe (see cmake/ScrapsBoundaryHash.cmake).
constexpr std::uint32_t kEngineAbiVersion = 1;

// ------------------------------------------------------------ layout hash
//
// A module built after the engine changed would read and write the exe's
// World with the wrong offsets, enum values or constants, or drive the exe's
// JobSystem with another protocol. Both sides compute this hash; the app
// refuses a module whose hash differs from its own. It mixes:
//   - kBoundarySourcesHash: the contents of every engine/core and
//     engine/platform header plus core/jobs.cpp and core/world.cpp, hashed
//     by CMake into a generated header. This is what catches two swapped
//     fields of the same size, a field's type changing at the same size, a
//     new enum value or a changed constant (kTickSeconds, kWorldExtent).
//   - kEngineAbiVersion, the compiler and its version, and the runtime
//     flavour (an MSVC Debug module has another heap and other container
//     sizes than a Release exe);
//   - the sizes and key field offsets of the types that cross the boundary,
//     JobSystem included. The source hash already covers what they show;
//     they stay as a second check that needs no build system.

namespace game_layout {

constexpr std::uint64_t mix(std::uint64_t hash, std::uint64_t value) {
  for (int i = 0; i < 8; ++i) {
    hash ^= (value >> (i * 8)) & 0xFFu;
    hash *= 0x100000001B3ull;  // FNV-1a prime
  }
  return hash;
}

#if defined(__clang__)
constexpr std::uint64_t kCompiler = 3;
#elif defined(_MSC_VER)
constexpr std::uint64_t kCompiler = 1;
#elif defined(__GNUC__)
constexpr std::uint64_t kCompiler = 2;
#else
constexpr std::uint64_t kCompiler = 0;
#endif

#if defined(__clang__)
constexpr std::uint64_t kCompilerVersion =
    static_cast<std::uint64_t>(__clang_major__) * 10000u + __clang_minor__ * 100u + __clang_patchlevel__;
#elif defined(_MSC_VER)
constexpr std::uint64_t kCompilerVersion = static_cast<std::uint64_t>(_MSC_FULL_VER);
#elif defined(__GNUC__)
constexpr std::uint64_t kCompilerVersion =
    static_cast<std::uint64_t>(__GNUC__) * 10000u + __GNUC_MINOR__ * 100u + __GNUC_PATCHLEVEL__;
#else
constexpr std::uint64_t kCompilerVersion = 0;
#endif

#if defined(_DEBUG)
constexpr std::uint64_t kDebugRuntime = 1;  // MSVC: the debug CRT, a different heap
#else
constexpr std::uint64_t kDebugRuntime = 0;
#endif

#if defined(_ITERATOR_DEBUG_LEVEL)
constexpr std::uint64_t kIteratorDebug = 10u + static_cast<std::uint64_t>(_ITERATOR_DEBUG_LEVEL);
#elif defined(_GLIBCXX_DEBUG)
constexpr std::uint64_t kIteratorDebug = 1;
#else
constexpr std::uint64_t kIteratorDebug = 0;
#endif

constexpr std::uint64_t compute() {
  std::uint64_t h = 0xCBF29CE484222325ull;  // FNV-1a offset basis
  h = mix(h, kBoundarySourcesHash);
  h = mix(h, kEngineAbiVersion);
  h = mix(h, kCompiler);
  h = mix(h, kCompilerVersion);
  h = mix(h, kDebugRuntime);
  h = mix(h, kIteratorDebug);
  h = mix(h, sizeof(void*));

  h = mix(h, sizeof(Vec2));
  h = mix(h, sizeof(Vec3));
  h = mix(h, sizeof(Color));
  h = mix(h, sizeof(EntityId));
  h = mix(h, sizeof(std::vector<Entity>));

  h = mix(h, sizeof(Entity));
  h = mix(h, offsetof(Entity, generation));
  h = mix(h, offsetof(Entity, alive));
  h = mix(h, offsetof(Entity, archetype));
  h = mix(h, offsetof(Entity, kind));
  h = mix(h, offsetof(Entity, flags));
  h = mix(h, offsetof(Entity, position));
  h = mix(h, offsetof(Entity, velocity));
  h = mix(h, offsetof(Entity, size));
  h = mix(h, offsetof(Entity, player));
  h = mix(h, offsetof(Entity, move_intent));
  h = mix(h, offsetof(Entity, facing));
  h = mix(h, offsetof(Entity, move_speed));
  h = mix(h, offsetof(Entity, on_ground));
  h = mix(h, offsetof(Entity, color));
  h = mix(h, offsetof(Entity, user));

  h = mix(h, sizeof(Command));
  h = mix(h, offsetof(Command, type));
  h = mix(h, offsetof(Command, player));
  h = mix(h, offsetof(Command, vec));
  h = mix(h, offsetof(Command, value));
  h = mix(h, sizeof(CommandList));
  h = mix(h, kMaxCommandsPerList);

  h = mix(h, sizeof(MovementRules));
  h = mix(h, sizeof(TileGrid));
  h = mix(h, sizeof(ImageDef));
  h = mix(h, sizeof(TileDef));
  h = mix(h, sizeof(Archetype));
  h = mix(h, sizeof(SoundDef));
  h = mix(h, sizeof(Level));
  h = mix(h, offsetof(Level, perspective));
  h = mix(h, offsetof(Level, images));
  h = mix(h, offsetof(Level, tiles));
  h = mix(h, offsetof(Level, grid));
  h = mix(h, offsetof(Level, archetypes));
  h = mix(h, offsetof(Level, player_archetype));
  h = mix(h, offsetof(Level, spawn_points));
  h = mix(h, offsetof(Level, sounds));
  h = mix(h, offsetof(Level, sky_top));
  h = mix(h, offsetof(Level, sky_bottom));

  h = mix(h, sizeof(World));
  h = mix(h, offsetof(World, tick));
  h = mix(h, offsetof(World, rng_state));
  h = mix(h, offsetof(World, rules));
  h = mix(h, offsetof(World, level));
  h = mix(h, offsetof(World, entities));
  h = mix(h, offsetof(World, free_slots));
  h = mix(h, offsetof(World, player_entities));

  // The exe owns the JobSystem; the module's copy of parallel_for writes it.
  h = mix(h, sizeof(JobSystem));

  h = mix(h, sizeof(GameBinding));
  h = mix(h, offsetof(GameBinding, pad));
  h = mix(h, sizeof(SoundEvents));
  h = mix(h, sizeof(GameUiCommand));
  h = mix(h, offsetof(GameUiCommand, command));
  h = mix(h, sizeof(GameApi));
  h = mix(h, offsetof(GameApi, ui_commands));
  h = mix(h, offsetof(GameApi, ui_command_count));
  return h;
}

}  // namespace game_layout

constexpr std::uint64_t kGameLayoutHash = game_layout::compute();

}  // namespace scraps

